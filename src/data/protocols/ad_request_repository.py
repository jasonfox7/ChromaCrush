"""Protocol interface for ad request repository."""

from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol
from uuid import UUID


class AdRequestRepositoryProtocol(Protocol):
    """Repository interface for ad requests (PostgreSQL)."""

    async def create(self, data: Any) -> Any: ...
    async def find_by_id(self, request_id: UUID) -> Any | None: ...
    async def update(self, request_id: UUID, changes: Any) -> Any: ...
    async def find_pending_by_player(self, player_id: UUID) -> list[Any]: ...
    async def find_last_by_type(self, player_id: UUID, ad_type: str) -> Any | None: ...
    async def expire_old_requests(self, before: datetime) -> int: ...
